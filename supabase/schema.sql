-- Jobdesk 1.4.0 PostgreSQL schema for Supabase.
-- This is schema ONLY. No fake users, jobs, spaces, or sample records.
-- Separate jobdesk schema keeps tables away from Supabase's exposed public Data API.
-- Run via Supabase SQL Editor, or let server initialization apply it.
BEGIN;
CREATE SCHEMA IF NOT EXISTS jobdesk;
REVOKE ALL ON SCHEMA jobdesk FROM PUBLIC;

CREATE TABLE IF NOT EXISTS jobdesk.users (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id text UNIQUE,
 name text NOT NULL,
 email text NOT NULL UNIQUE,
 role text NOT NULL,
 active integer NOT NULL DEFAULT 1,
 is_owner integer NOT NULL DEFAULT 0,
 created_at text NOT NULL,
 deleted_at text
);
CREATE TABLE IF NOT EXISTS jobdesk.job_spaces (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE,
 owner_user_id integer REFERENCES jobdesk.users(id),
 sort_order integer NOT NULL DEFAULT 0,
 created_at text NOT NULL,
 archived_at timestamptz
);
ALTER TABLE jobdesk.job_spaces ADD COLUMN IF NOT EXISTS archived_at timestamptz;
CREATE TABLE IF NOT EXISTS jobdesk.jobs (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id text UNIQUE,
 name text NOT NULL,
 customer text NOT NULL,
 contact text NOT NULL DEFAULT '',
 date_in text NOT NULL,
 due_date text NOT NULL,
 priority text NOT NULL,
 status text NOT NULL DEFAULT 'Awaiting Sales',
 assigned_to integer REFERENCES jobdesk.users(id),
 created_by integer NOT NULL REFERENCES jobdesk.users(id),
 created_at text NOT NULL,
 updated_at text NOT NULL,
 confirmed_by integer REFERENCES jobdesk.users(id),
 confirmed_at text,
 quantity integer NOT NULL DEFAULT 1,
 size text NOT NULL DEFAULT '',
 material text NOT NULL DEFAULT '',
 finishing text NOT NULL DEFAULT '',
 notes text NOT NULL DEFAULT '',
 artwork_url text NOT NULL DEFAULT '',
 print_file_url text NOT NULL DEFAULT '',
 artwork_approved integer NOT NULL DEFAULT 0,
 print_checked integer NOT NULL DEFAULT 0,
 version integer NOT NULL DEFAULT 1,
 space_id integer REFERENCES jobdesk.job_spaces(id),
 deleted_from_status text,
 production_status text,
 production_updated_at text
);
CREATE TABLE IF NOT EXISTS jobdesk.activity (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id integer REFERENCES jobdesk.jobs(id),
 user_id integer NOT NULL REFERENCES jobdesk.users(id),
 action text NOT NULL,
 created_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS jobdesk.device_profiles (
 device_key text PRIMARY KEY,
 device_label text NOT NULL,
 user_id integer NOT NULL REFERENCES jobdesk.users(id),
 last_seen text NOT NULL,
 created_at text NOT NULL
);
-- Private, revocable invitation hashes; create real links outside GitHub.
CREATE TABLE IF NOT EXISTS jobdesk.workspace_access (
 token_hash text PRIMARY KEY CHECK (length(token_hash)=64),
 created_at timestamptz NOT NULL DEFAULT now(),
 revoked_at timestamptz
);
-- Admin PIN hashes are provisioned privately and NEVER committed to GitHub.
CREATE TABLE IF NOT EXISTS jobdesk.admin_auth (
 id boolean PRIMARY KEY DEFAULT true,
 pin_hash text NOT NULL,
 failed_attempts integer NOT NULL DEFAULT 0,
 locked_until timestamptz,
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jobdesk.admin_sessions (
 token_hash text PRIMARY KEY,
 device_key text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL
);
-- V2.0 staff access is provisioned only by Admin; no email or staff PIN required.
CREATE TABLE IF NOT EXISTS jobdesk.staff_invites (
 token_hash text PRIMARY KEY CHECK(length(token_hash)=64),
 user_id integer NOT NULL REFERENCES jobdesk.users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL,
 redeemed_at timestamptz
);
CREATE TABLE IF NOT EXISTS jobdesk.staff_sessions (
 token_hash text PRIMARY KEY CHECK(length(token_hash)=64),
 user_id integer NOT NULL REFERENCES jobdesk.users(id),
 device_key text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL,
 revoked_at timestamptz
);
-- Indexes reported by Supabase's foreign-key performance advisor.
CREATE INDEX IF NOT EXISTS activity_user ON jobdesk.activity(user_id);
CREATE INDEX IF NOT EXISTS job_spaces_owner ON jobdesk.job_spaces(owner_user_id);
CREATE INDEX IF NOT EXISTS jobs_assigned ON jobdesk.jobs(assigned_to);
CREATE INDEX IF NOT EXISTS jobs_confirmed_by ON jobdesk.jobs(confirmed_by);
CREATE INDEX IF NOT EXISTS jobs_created_by ON jobdesk.jobs(created_by);
CREATE INDEX IF NOT EXISTS jobs_space ON jobdesk.jobs(space_id);
CREATE INDEX IF NOT EXISTS staff_invites_user ON jobdesk.staff_invites(user_id);
CREATE INDEX IF NOT EXISTS staff_sessions_user ON jobdesk.staff_sessions(user_id);
CREATE INDEX IF NOT EXISTS staff_sessions_device ON jobdesk.staff_sessions(device_key);
REVOKE ALL ON ALL TABLES IN SCHEMA jobdesk FROM PUBLIC, anon, authenticated;

CREATE INDEX IF NOT EXISTS jobs_due ON jobdesk.jobs(due_date,status);
CREATE INDEX IF NOT EXISTS activity_job ON jobdesk.activity(job_id,id);
CREATE INDEX IF NOT EXISTS device_profiles_member ON jobdesk.device_profiles(user_id);
COMMIT;
