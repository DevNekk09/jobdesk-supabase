import {test,expect} from '@playwright/test';
const date=(offset:number)=>new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Kuala_Lumpur',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(Date.now()+offset*86400000));
const member={id:31,name:'Designer Test',role:'Designer',email:'designer@local.invalid',active:true};
const space={id:50,name:'Designer Test',owner_user_id:31,sort_order:1};
const job={id:991,name:'V3 regression job',invoice_id:'INTERNAL-991',date_in:date(-3),due_date:date(0),status:'Confirmed',priority:'Normal',space_id:50,assigned_to:31,confirmed_at:new Date().toISOString(),created_at:new Date().toISOString(),version:1};
test('V3 focus, view switcher, global search, notifications and versioned undo',async({page})=>{
 let current={...job},undoCalls=0;
 await page.route('**/api/bootstrap*',r=>r.fulfill({json:{me:member,users:[member],spaces:[space],jobs:[current],activity:[],devices:[],available_months:[date(0).slice(0,7)],overdue_total:0,csrf:'',hosted:true}}));
 await page.route('**/api/jobs/991',r=>r.fulfill({json:{job:current,activity:[]}}));
 await page.route('**/api/jobs/991/progress',r=>{expect(r.request().postDataJSON().version).toBe(1);current={...current,status:'Preparing Master Files',version:2};return r.fulfill({json:{job:current}})});
 await page.route('**/api/jobs/991/undo-progress',r=>{expect(r.request().postDataJSON().version).toBe(2);undoCalls++;current={...current,status:'Confirmed',version:3};return r.fulfill({json:{job:current}})});
 await page.goto('/');
 await expect(page.getByRole('region',{name:"Today's focus"})).toBeVisible();
 await page.locator('.v30-focus .focus-today').click();
 const list=page.locator('.job-panel.ticket-list');
 await expect(list.locator('.job-link')).toHaveText('V3 regression job');
 await list.getByRole('button',{name:'List',exact:true}).click();
 await expect(list).toHaveClass(/view-list/);
 await list.getByRole('button',{name:'Board',exact:true}).click();
 await expect(list.locator('.v30-board-job')).toHaveCount(1);
 await list.getByRole('button',{name:'Ticket',exact:true}).click();
 await list.getByRole('button',{name:'Advance V3 regression job'}).click();
 await expect(page.locator('.job-save-feedback')).toContainText('Progress updated');
 await page.locator('.v30-toast-undo').click();
 await expect.poll(()=>undoCalls).toBe(1);
 await expect(list.locator('.ticket-progress')).toContainText('Confirmed');
 await page.getByRole('button',{name:'Global search',exact:true}).click();
 await page.getByRole('textbox',{name:'Search all workspace jobs'}).fill('regression');
 await expect(page.locator('.v30-utility-list button')).toContainText('V3 regression job');
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('button',{name:'Notifications',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('V3 regression job');
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.setViewportSize({width:390,height:844});
 const dimensions=await page.evaluate(()=>({doc:document.documentElement.scrollWidth,width:innerWidth}));
 expect(dimensions.doc).toBeLessThanOrEqual(dimensions.width+1);
});
